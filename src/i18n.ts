function translateFor(source: string, target: Locale): string {
  if (target === 'zh-CN') return zhCnEntries[source] || source
  const index = { 'zh-TW': 0, en: 1, ko: 2 }[target] as 0 | 1 | 2
  const exact = (entries[source] || entries[source.trim()])?.[index]
  if (exact) return exact
  const action = source.match(/^正在(.+) (.+)$/)
  if (action) {
    const actionMap: Record<string, [string, string, string]> = {
      '刷新': ['重新整理', 'Refreshing', '새로 고치는 중'],
      '安装': ['安裝', 'Installing', '설치 중'],
      '卸载': ['解除安裝', 'Uninstalling', '제거 중'],
      '删除': ['刪除', 'Deleting', '삭제 중'],
      '检查': ['檢查', 'Checking', '확인 중'],
      '保存': ['儲存', 'Saving', '저장 중'],
      '导出': ['匯出', 'Exporting', '내보내는 중'],
      '复制': ['複製', 'Copying', '복사 중'],
      '导入': ['匯入', 'Importing', '가져오는 중'],
      '打开': ['開啟', 'Opening', '여는 중'],
      '创建': ['建立', 'Creating', '생성 중'],
      '恢复': ['恢復', 'Restoring', '복원 중'],
      '切换': ['切換', 'Switching', '전환 중'],
      '准备': ['準備', 'Preparing', '준비 중'],
      '重新安装': ['重新安裝', 'Reinstalling', '재설치 중'],
    }
    const translatedAction = actionMap[action[1]]?.[index]
    if (translatedAction) return `${translatedAction} ${action[2]}`
  }
  const simpleAction = source.match(/^(安装|卸载|更新|恢复) (.+)$/)
  if (simpleAction) {
    const actionMap: Record<string, [string, string, string]> = {
      '安装': ['安裝', 'Install', '설치'],
      '卸载': ['解除安裝', 'Uninstall', '제거'],
      '更新': ['更新', 'Update', '업데이트'],
      '恢复': ['恢復', 'Restore', '복원'],
    }
    const translatedAction = actionMap[simpleAction[1]]?.[index]
    if (translatedAction) return `${translatedAction} ${simpleAction[2]}`
  }
  const prefixed = source.match(/^(备注：|产品名称：|产品名称未知 · )(.+)$/)
  if (prefixed) {
    const prefixMap: Record<string, [string, string, string]> = {
      '备注：': ['備註：', 'Note: ', '메모: '],
      '产品名称：': ['產品名稱：', 'Product name: ', '제품 이름: '],
      '产品名称未知 · ': ['產品名稱未知 · ', 'Unknown product name · ', '제품 이름 알 수 없음 · '],
    }
    return `${prefixMap[prefixed[1]]?.[index] || prefixed[1]}${prefixed[2]}`
  }
  return source
}

export function t(source: string): string { return translateFor(source, locale.value) }

export function useLocaleTranslation() {
  function setLocale(next: Locale) {
    locale.value = next
    localStorage.setItem('oc2-locale', next)
    document.documentElement.lang = next
  }
  return { locale, setLocale, t }
}
