function withLocation(copy: Localized): Localized {
  return {
    'zh-CN': `${copy['zh-CN']}\n位置：{path}`,
    'zh-TW': `${copy['zh-TW']}\n位置：{path}`,
    en: `${copy.en}\nLocation: {path}`,
    ko: `${copy.ko}\n위치: {path}`,
    ja: `${copy.ja}\n場所：{path}`,
  }
}

