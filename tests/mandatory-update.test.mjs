import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'

const source = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const offer = { version: '9.9.9', current_version: '2.4.2', background_install: true, source_channel: 'github-direct' }
const verified = { ...offer, version: '10.0.0', body: 'Verified release notes' }
const result = (patch = {}) => ({ channels: [], all_failed: false, region: 'cn', update: offer, ...patch })
let instance = 0
const fresh = () => import(`../src/appUpdateState.ts?test=${++instance}`)

test('startup recovery gate only becomes mandatory when a newer version can be selected', async () => {
  const state = await fresh()
  state.setCheckingUpdateRecovery(true)
  assert.equal(state.appUpdateBlocksOperations(), true)
  assert.equal(state.beginAppUpdateCheck(), true)
  state.finishAppUpdateCheck(result({ update: null, recovery_required: true }))
  assert.equal(state.appUpdateState.stage, 'current')
  state.setCheckingUpdateRecovery(false)
  assert.equal(state.appUpdateBlocksOperations(), false)
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result({ all_failed: true, recovery_required: true }))
  assert.equal(state.appUpdateState.stage, 'checkFailed')
  assert.equal(state.appUpdateBlocksOperations(), false)
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result({ recovery_required: true }))
  assert.equal(state.appUpdateState.stage, 'recovery')
  assert.equal(state.appUpdateBlocksOperations(), true)
  assert.equal(state.beginAppUpdateRecovery(), true)
  assert.equal(state.beginAppUpdateRecovery(), false)
  state.failAppUpdateRecovery('browser unavailable')
  assert.equal(state.appUpdateState.error, 'browser unavailable')
  assert.equal(state.appUpdateState.stage, 'recovery')
  assert.equal(state.beginAppUpdateRecovery(), true)
})

test('checking, downloading, download failures and deferred installation permit normal operations', async () => {
  const state = await fresh()
  assert.equal(state.beginAppUpdateCheck(), true)
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.finishAppUpdateCheck(result()), 'github-direct')
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.beginAppUpdateCheck(), false)
  state.setBackgroundAppUpdateProgress({ downloaded: 512, total: 1024 })
  assert.equal(state.appUpdateState.progress.downloaded, 512)
  state.finishBackgroundAppUpdate({ error: 'offline' })
  assert.equal(state.appUpdateState.stage, 'stageFailed')
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.appUpdateState.progress, null)
  assert.equal(state.retryBackgroundAppUpdate(), 'github-direct')
  assert.equal(state.retryBackgroundAppUpdate(), undefined)
  state.finishBackgroundAppUpdate({ update: verified })
  assert.equal(state.appUpdateState.stage, 'ready')
  assert.equal(state.appUpdateState.update.version, verified.version)
  assert.equal(state.appUpdateState.update.body, verified.body)
  assert.equal(state.appUpdateState.notesPending, true)
  state.dismissAppUpdateNotes()
  assert.equal(state.appUpdateState.notesPending, false)
  assert.equal(state.appUpdateState.stage, 'ready')
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.beginStagedAppUpdate(), true)
  assert.equal(state.appUpdateBlocksOperations(), true)
  state.finishStagedAppUpdate()
  assert.equal(state.appUpdateState.stage, 'handoff')
  assert.equal(state.appUpdateBlocksOperations(), true)
})

test('latest stage response clears the stale offer, and OS status never starts staging', async () => {
  const state = await fresh()
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result())
  state.finishBackgroundAppUpdate({ update: null })
  assert.equal(state.appUpdateState.stage, 'current')
  assert.equal(state.appUpdateState.update, null)
  assert.equal(state.appUpdateState.notesPending, false)
  for (const [installation_status, expected] of [['reboot_required', 'systemReboot'], ['applying', 'systemApplying'], ['restart_failed', 'restartFailed']]) {
    assert.equal(state.beginAppUpdateCheck(), true)
    assert.equal(state.finishAppUpdateCheck(result({ installation_status })), undefined)
    assert.equal(state.appUpdateState.stage, expected)
    assert.equal(state.appUpdateBlocksOperations(), false)
  }
})

test('unsupported installer and application failure are checkable but never retry the same file', async () => {
  const state = await fresh()
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result())
  state.finishBackgroundAppUpdate({ error: 'update.deferredUnsupported' })
  assert.equal(state.appUpdateState.stage, 'stageFailed')
  assert.equal(state.retryBackgroundAppUpdate(), undefined)
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result())
  state.finishBackgroundAppUpdate({ update: verified })
  state.beginStagedAppUpdate()
  state.finishStagedAppUpdate('update.installFailedManual')
  assert.equal(state.appUpdateState.stage, 'stageFailed')
  assert.equal(state.retryBackgroundAppUpdate(), undefined)
  assert.equal(state.beginAppUpdateCheck(), true)
})

