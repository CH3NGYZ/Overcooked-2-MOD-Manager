import assert from 'node:assert/strict'
import test from 'node:test'
import {readFileSync,existsSync} from 'node:fs'
const read=path=>readFileSync(new URL(`../${path}`,import.meta.url),'utf8')
const dialog=read('src/modChanges/ChangePlanDialog.vue'),app=read('src/App.vue'),details=read('src/modChanges/ChangePlanDetails.vue'),item=read('src/modChanges/ChangePlanItem.vue')
test('App owns the only shared plan modal and all pages use its store',()=>{
 assert.equal((app.match(/<ChangePlanDialog\s*\/>/g)||[]).length,1)
 for(const name of ['ModsLocalView','ModsOnlineView','LevelsView','MapsOnlineView'])assert.doesNotMatch(read(`src/views/${name}.vue`),/<(?:ChangePlanDialog|InstallCheckDialog|InstallPlanDialog|ModInstallNoteDialog)/)
 for(const path of ['components/InstallCheckDialog.vue','components/InstallPlanDialog.vue','components/ModInstallDialog.vue','components/ModInstallNoteDialog.vue','composables/useInstallPlanGate.ts'])assert.equal(existsSync(new URL(`../src/${path}`,import.meta.url)),false,path)
})
test('confirmation shows a compact item list and preserves full reasons and package states inside collapsed details',()=>{
 for(const pattern of [/root\.tag/,/in plan\.actions/,/action\.caused_by/,/in node\.members/,/member\.enabled/,/member\.dll_file/])assert.match(details,pattern)
 for(const pattern of [/row\.action\.from_tag/,/row\.action\?\.to_tag/])assert.match(item,pattern)
 assert.match(details,/<details class="plan-details">/);assert.doesNotMatch(details,/<details[^>]+open/)
 assert.match(dialog,/in plan\.blockers/);assert.match(dialog,/blocker\.owner_id/);assert.match(dialog,/v-for="row in rows"/)
 assert.doesNotMatch(dialog,/api\.(?:install|toggle|uninstall)|execute\(action|done\.value|failures\.value/)
})
test('blocked and busy plans cannot confirm; failure can only replan; preparation and execution cannot cancel',()=>{
 assert.match(dialog,/state\?\.phase === 'failed'/);assert.match(dialog,/plan\?\.status !== 'ready'/)
 assert.match(dialog,/\['preparing', 'executing'\]\.includes/);assert.match(dialog,/:disabled="!canCancel"/)
 assert.match(dialog,/@click="changes\.confirm"/)
 assert.match(dialog,/@click="changes\.retry"/)
})
test('the shared plan dialog alternates between the first-install note and plan confirmation',()=>{
 assert.match(dialog,/<ModInstallNoteDialog v-if="installNotes\.length" :notes="installNotes"\s+@continue="changes\.acceptInstallNotes" @cancel="changes\.cancel"\s*\/>\s*<AppModal v-else/)
 assert.doesNotMatch(dialog,/v-html|setInterval|readingSeconds/)
})
test('map selection and manual preview never pre-uninstall or execute individual rows',()=>{
 const map=read('src/composables/useLevelSetImport.ts'),manual=read('src/composables/useModInstallFlow.ts')
 assert.ok(map.indexOf('await askApproval(staged.path, sets)')<map.indexOf('await changes.run('))
 assert.match(map,/map_import:/);assert.match(manual,/node_id: `preview:/)
 for(const source of [map,manual])assert.doesNotMatch(source,/api\.(?:deleteLevelSet|uninstallLocalMod|confirmModInstall|importLevelSets)\(/)
})
test('online selection freezes the exact release or RAW candidate before shared confirmation',()=>{
 const source=read('src/composables/useModRepositoryPreview.ts')
 assert.match(source,/candidate_id: raw \? `raw:/);assert.match(source,/`release:\$\{repo\.id\}:\$\{release!\.tag_name\}`/)
 assert.match(source,/asset_name: assetName/);assert.doesNotMatch(source,/prepareInstall|dialog\.warning|api\.installModRepository/)
})
test('planning stays indeterminate; task-local bytes use the shared race overlay while rows keep compact status',()=>{
 const strip=read('src/components/DownloadStrip.vue')
 assert.match(dialog,/state\?\.phase === 'planning' \|\| state\?\.phase === 'preparing'/)
 assert.match(dialog,/<NProgress[^>]+:show-indicator="false"[^>]+processing/)
 assert.match(dialog,/modChanges\.progress\.planning/);assert.match(dialog,/modChanges\.progress\.preparing/)
 assert.match(dialog,/modChanges\.progress\.packages/);assert.match(dialog,/:percentage="completion.percentage \?\? 0"/)
 assert.ok(dialog.indexOf('<template #footer>')<dialog.indexOf('class="progress-heading"'),'overall progress remains in the fixed footer')
 assert.equal((app.match(/<DownloadStrip\s*\/>/g)||[]).length,1)
 assert.doesNotMatch(dialog,/watchDownloadProgress|<DownloadStrip|speed_bytes|downloaded/)
 const store=read('src/modChanges/store.ts')
 assert.match(store,/beginDownloadTask/);assert.match(store,/endDownloadTask\(token\)/)
 assert.match(store,/progressSource: 'caller'/);assert.match(store,/cancel: cancelPreparationDownload/)
 assert.match(store,/updateDownloadProgress\([\s\S]*?, token\)/)
 assert.doesNotMatch(item,/<NProgress|<DownloadVolumes|formatFileSize|speed_bytes|item-download/)
 assert.match(strip,/<Teleport to="body">/)
 assert.doesNotMatch(strip,/downloadInlineTarget|mod-changes|dl-inline/)
 assert.equal((strip.match(/void watchDownloadProgress\(/g)||[]).length,1)
 assert.match(strip,/formatFileSize\(progress\.downloaded\)/);assert.match(strip,/formatFileSize\(progress\.total\)/)
})
