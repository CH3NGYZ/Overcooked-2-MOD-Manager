test('system installation and reboot block another installer; a failed recheck does not dismiss either', async () => {
  const state = await fresh()
  state.beginAppUpdateCheck()
  assert.equal(state.finishAppUpdateCheck(result({ installation_status: 'applying' })), undefined)
  assert.equal(state.appUpdateState.stage, 'systemApplying')
  assert.equal(state.canExitForAppUpdate('download'), false)
  assert.equal(state.canExitForAppUpdate('reboot'), false)
  assert.equal(state.appUpdateBlocksOperations(), true)
  assert.equal(state.beginAppUpdateCheck(), true)
  assert.equal(state.appUpdateState.recheckingStatus, true)
  assert.equal(state.appUpdateState.stage, 'systemApplying')
  state.finishAppUpdateCheck(result({ update: null, all_failed: true }))
  assert.equal(state.appUpdateState.stage, 'systemApplying')
  assert.equal(state.appUpdateState.update.version, offer.version)
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result({ installation_status: 'reboot_required' }))
  assert.equal(state.appUpdateState.stage, 'systemReboot')
  assert.equal(state.canExitForAppUpdate('download'), false)
  assert.equal(state.canExitForAppUpdate('apply'), false)
  assert.equal(state.beginAppUpdateExit('reboot'), true)
  state.finishAppUpdateExit('systemReboot', 'assetBundle.recoveryPending')
  assert.equal(state.appUpdateState.stage, 'systemReboot')
  assert.equal(state.appUpdateState.error, 'assetBundle.recoveryPending')
  assert.equal(state.canExitForAppUpdate('reboot'), true)
  assert.equal(state.beginAppUpdateCheck(), true)
  assert.equal(state.appUpdateState.stage, 'systemReboot')
  assert.equal(state.appUpdateState.recheckingStatus, true)
  assert.equal(state.beginAppUpdateCheck(), false)
  state.finishAppUpdateCheck(result({ update: null, installation_status: 'restart_failed' }))
  assert.equal(state.appUpdateState.stage, 'stageFailed')
  assert.equal(state.appUpdateState.update.version, offer.version)
  assert.equal(state.canExitForAppUpdate('download'), true)
  assert.equal(state.canCheckAppUpdate(), false)
})

