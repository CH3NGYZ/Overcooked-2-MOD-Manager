import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'

const source = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const offer = { version: '9.9.9', current_version: '2.4.2', install_mode: 'deferred', source_channel: 'github-direct' }
const verified = { ...offer, version: '10.0.0', body: 'Verified release notes' }
const result = (patch = {}) => ({ channels: [], all_failed: false, region: 'cn', update: offer, ...patch })
let instance = 0
const fresh = () => import(`../src/appUpdateState.ts?test=${++instance}`)

test('unconfirmed, current, and Store results do not introduce a mandatory update', async () => {
  const state = await fresh()
  assert.equal(state.beginAppUpdateCheck(), true)
  assert.equal(state.appUpdateBlocksOperations(), false)
  state.finishAppUpdateCheck(result({ update: null, recovery_required: true }))
  assert.equal(state.appUpdateState.stage, 'current')
  assert.equal(state.appUpdateBlocksOperations(), false)
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result({ update: null, all_failed: true, recovery_required: true }))
  assert.equal(state.appUpdateState.stage, 'checkFailed')
  assert.equal(state.appUpdateBlocksOperations(), false)
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result({ distribution: 'microsoft_store' }))
  assert.equal(state.appUpdateState.update, null)
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.beginAppUpdateCheck(), false)
})

test('a standalone offer downloads in the background and offers to apply only after staging', async () => {
  const state = await fresh()
  assert.equal(state.beginAppUpdateCheck(), true)
  assert.equal(state.finishAppUpdateCheck(result()), 'github-direct')
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.beginAppUpdateCheck(), false)
  assert.equal(state.canExitForAppUpdate('download'), false)
  assert.equal(state.canExitForAppUpdate('apply'), false)
  state.setBackgroundAppUpdateProgress({ downloaded: 512, total: 1024 })
  assert.equal(state.appUpdateState.progress.downloaded, 512)
  state.finishBackgroundAppUpdate({ update: verified })
  assert.equal(state.appUpdateState.stage, 'ready')
  assert.equal(state.appUpdateState.update.version, verified.version)
  assert.equal(state.appUpdateState.update.body, verified.body)
  assert.equal(state.appUpdateState.notesRequested, true)
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.beginAppUpdateExit('apply'), true)
  state.finishAppUpdateExit('ready')
  assert.equal(state.appUpdateState.stage, 'handoff')
  assert.equal(state.appUpdateBlocksOperations(), true)
})

test('only a successful, version-bound defer schedules installation on normal exit', async () => {
  const state = await fresh()
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result())
  assert.equal(state.beginDeferringAppUpdate(), undefined)
  state.finishBackgroundAppUpdate({ update: verified })
  assert.equal(state.beginDeferredAppUpdateExit(), false)
  assert.equal(state.beginDeferringAppUpdate(), verified.version)
  assert.equal(state.beginDeferringAppUpdate(), undefined)
  assert.equal(state.appUpdateBlocksOperations(), true)
  state.finishDeferringAppUpdate()
  assert.equal(state.appUpdateState.deferred, true)
  assert.equal(state.appUpdateState.notesRequested, false)
  assert.equal(state.appUpdateBlocksOperations(), false)
  state.presentAppUpdate()
  assert.equal(state.appUpdateState.notesRequested, false)
  assert.equal(state.beginDeferredAppUpdateExit(), true)
  state.finishAppUpdateExit('ready', 'modChanges.recoveryRequired')
  assert.equal(state.appUpdateState.deferred, true)
  assert.equal(state.appUpdateBlocksOperations(), false)
  assert.equal(state.beginDeferredAppUpdateExit(), true)
  state.finishAppUpdateExit('ready')
  assert.equal(state.appUpdateState.stage, 'handoff')
})

test('download, signature and defer failures leave only mandatory manual destinations', async () => {
  for (const error of ['offline', 'update.verifyFailed', 'update.stagedUnavailable']) {
    const state = await fresh()
    state.beginAppUpdateCheck()
    state.finishAppUpdateCheck(result())
    if (error === 'update.stagedUnavailable') {
      state.finishBackgroundAppUpdate({ update: verified })
      state.beginDeferringAppUpdate()
      state.finishDeferringAppUpdate(error)
    } else state.finishBackgroundAppUpdate({ error })
    assert.equal(state.appUpdateState.error, error)
    assert.equal(state.appUpdateState.stage, 'stageFailed')
    assert.equal(state.appUpdateState.progress, null)
    assert.equal(state.appUpdateState.deferred, false)
    assert.equal(state.appUpdateBlocksOperations(), true)
    assert.equal(state.beginDeferringAppUpdate(), undefined)
    assert.equal(state.canExitForAppUpdate('apply'), false)
    assert.equal(state.canExitForAppUpdate('download'), true)
    assert.equal(state.canExitForAppUpdate('website'), true)
  }
})

