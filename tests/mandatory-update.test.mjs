test('browser or handshake failure keeps the modal; an unsafe relaunch leaves only manual downloads', async () => {
  for (const tag of ['update.restartAsUserFailed', 'update.restartAsUserUnavailable']) {
    const state = await fresh()
    state.beginAppUpdateCheck()
    state.finishAppUpdateCheck(result({ update: { ...offer, install_mode: 'restartAsUser' } }))
    assert.equal(state.beginAppUpdateExit('apply'), true)
    const error = `${tag}?reason=Unable%20to%20reopen`
    state.finishAppUpdateExit('ready', error, tag)
    assert.equal(state.appUpdateState.error, error)
    assert.equal(state.appUpdateState.stage, 'stageFailed')
    assert.equal(state.canExitForAppUpdate('apply'), false)
  }
  const state = await fresh()
  state.beginAppUpdateCheck()
  state.finishAppUpdateCheck(result({ update: { ...offer, install_mode: 'manual' } }))
  assert.equal(state.beginAppUpdateExit('download'), true)
  state.finishAppUpdateExit('stageFailed', 'update.pageOpenFailed')
  assert.equal(state.appUpdateState.error, 'update.pageOpenFailed')
  assert.equal(state.appUpdateState.stage, 'stageFailed')
  assert.equal(state.appUpdateBlocksOperations(), true)
  assert.equal(state.beginAppUpdateExit('download'), true)
  state.finishAppUpdateExit('stageFailed')
  assert.equal(state.appUpdateState.stage, 'handoff')
})

